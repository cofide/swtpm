#!/bin/sh

# This is an entrypoint script for the swtpm Dockerfile
# It will do the following:
# * Create TPMCERTS_DIR, $TPMSTATE_DIR if they do not already exist
# * Perform swtpm_setup bootstrap (creates EK)
# * Opens swtpm char device at /run/swtpm
# * Writes EK certificate hash to $TPMHASHES_DIR/ek-cert.sha256

set -euo pipefail
 
TPMCERTS_DIR=${TPMCERTS_DIR:-/tpmcerts}
TPMHASHES_DIR=${TPMHASHES_DIR:-/tpmhashes}
TPMSTATE_DIR=${TPMSTATE_DIR:-/tpmstate}
TPMSOCK_DIR=${TPMSOCK_DIR:-/run/swtpm}

mkdir -p $TPMCERTS_DIR $TPMSTATE_DIR
    
echo "Running swtpm_setup..."
# Run the setup command for TPM 2.0
/usr/bin/swtpm_setup \
  --tpm2 \
  --tpmstate $TPMSTATE_DIR \
  --create-ek-cert \
  --create-platform-cert \
  --write-ek-cert-files $TPMCERTS_DIR \
  --lock-nvram

echo "Starting swtpm socket..."
/usr/bin/swtpm socket --tpm2 \
  --tpmstate dir=$TPMSTATE_DIR \
  --ctrl type=unixio,path=$TPMSOCK_DIR/tpm.sock.ctrl \
  --server type=unixio,path=$TPMSOCK_DIR/tpm.sock \
  --flags not-need-init &

EK_CERT_HASH=$(openssl x509 -in \
  $TPMCERTS_DIR/ek-rsa2048.crt -pubkey -noout \
  | openssl pkey -pubin -outform DER \
  | openssl dgst -sha256 \
  | awk '{print $2}')

# TODO: Make allowlist of hashes populate from
# key materials generated by swtpm_setup
echo -n $EK_CERT_HASH > $TPMHASHES_DIR/ek-cert.sha256

# Wait for socket to become available before
# beginning tmp2_tools-based calls to initialise
sleep 1

# Explicitly start the TPM instance
echo "Starting TPM instance..."
export TPM2TOOLS_TCTI="swtpm:path=$TPMSOCK_DIR/tpm.sock"
tpm2_startup -c -T "swtpm:path=/run/swtpm/tpm.sock"

# Wait for swtpm socket process to exit.
echo "Running..."
wait
